#!/usr/bin/env python3
import glob
import json
import os
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAP = ROOT / "scripts" / "icon-packs.json"
OUT = ROOT / "crates" / "app" / "assets" / "icon-packs"
RS = ROOT / "crates" / "app" / "src" / "icon_packs.rs"
SPECS = {
    "iconoir": "iconoir@7.12.1",
    "remix": "remixicon@4.9.1",
    "solar": "@iconify-json/solar@1.2.13",
}
SVG_NS = "http://www.w3.org/2000/svg"
SOLAR_WRAP = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">%s</svg>'


def fail(msg):
    sys.exit("error: " + msg)


def fetch(spec):
    pack_dir = tempfile.mkdtemp(prefix="aether-pack-")
    r = subprocess.run(["npm", "pack", "--ignore-scripts", spec], cwd=pack_dir, capture_output=True, text=True)
    if r.returncode:
        fail(f"npm pack {spec}: {r.stderr.strip()}")
    tgz = glob.glob(os.path.join(pack_dir, "*.tgz"))
    if len(tgz) != 1:
        fail(f"{spec}: expected one tarball in {pack_dir}")
    dest = tempfile.mkdtemp(prefix="aether-unpack-")
    subprocess.run(["tar", "-xzf", tgz[0], "-C", dest], check=True)
    return Path(dest) / "package"


def index_files(base, suffix):
    found = {}
    for dirpath, dirnames, filenames in os.walk(base):
        for name in dirnames + filenames:
            if os.path.islink(os.path.join(dirpath, name)):
                fail(f"symlink in package: {dirpath}/{name}")
        for name in filenames:
            if name.endswith(suffix):
                stem = name[: -len(".svg")]
                if stem in found:
                    fail(f"ambiguous icon name {stem}")
                found[stem] = Path(dirpath) / name
    return found


def validate(label, text):
    if not text.startswith("<svg"):
        fail(f"{label}: does not start with <svg")
    for banned in ("<!DOCTYPE", "<!ENTITY", "<script", "foreignObject", "href"):
        if banned.lower() in text.lower():
            fail(f"{label}: contains {banned}")
    try:
        root = ET.fromstring(text)
    except ET.ParseError as e:
        fail(f"{label}: not valid XML: {e}")
    if root.tag not in ("svg", f"{{{SVG_NS}}}svg"):
        fail(f"{label}: root is {root.tag}, not svg")
    for el in root.iter():
        tag = el.tag.rsplit("}", 1)[-1].lower()
        if tag in ("script", "foreignobject"):
            fail(f"{label}: <{tag}> element")
        for attr in el.attrib:
            local = attr.rsplit("}", 1)[-1].lower()
            if local.startswith("on") or local == "href":
                fail(f"{label}: attribute {attr}")


def main():
    mapping = json.loads(MAP.read_text())
    sources = {}
    for pack, spec in SPECS.items():
        base = fetch(spec)
        if pack == "iconoir":
            sources[pack] = index_files(base / "icons" / "regular", ".svg")
        elif pack == "remix":
            sources[pack] = index_files(base / "icons", "-line.svg")
        else:
            sources[pack] = json.loads((base / "icons.json").read_text())["icons"]

    for pack in SPECS:
        (OUT / pack).mkdir(parents=True, exist_ok=True)
        for old in (OUT / pack).glob("*.svg"):
            old.unlink()

    entries = []
    counts = {}
    for pack in SPECS:
        mapped = 0
        for lucide, row in sorted(mapping.items()):
            name = row[pack]
            if name is None:
                continue
            if pack == "solar":
                if name not in sources[pack]:
                    fail(f"solar: {name} (for {lucide}) not found")
                text = SOLAR_WRAP % sources[pack][name]["body"]
            else:
                if name not in sources[pack]:
                    fail(f"{pack}: {name} (for {lucide}) not found")
                text = sources[pack][name].read_text(encoding="utf-8").strip()
            validate(f"{pack}/{lucide}", text)
            (OUT / pack / f"{lucide}.svg").write_text(text + "\n", encoding="utf-8")
            entries.append((f"icons/pack/{pack}/{lucide}.svg", f"../assets/icon-packs/{pack}/{lucide}.svg"))
            mapped += 1
        counts[pack] = (mapped, len(mapping) - mapped)

    entries.sort()
    lines = ["// Generated by scripts/vendor-icon-packs.py; do not edit.", "#[rustfmt::skip]", "pub(crate) static PACK_ICONS: &[(&str, &[u8])] = &["]
    for key, rel in entries:
        lines.append(f'    ("{key}", include_bytes!("{rel}")),')
    lines.append("];")
    RS.write_text("\n".join(lines) + "\n")

    for pack, (mapped, null) in counts.items():
        print(f"{pack}: {mapped} mapped, {null} null")


if __name__ == "__main__":
    main()
